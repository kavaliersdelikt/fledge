// ---------------------------------------------------------------------------------------------------------------------------
// Database schema
// ---------------------------------------------------------------------------------------------------------------------------
{
  const sql = read('db', 'schema.sql');
  type Col = { name: string; type: string; later: boolean };
  const tables = new Map<string, { cols: Col[]; note: string }>();
  const splitTop = (s: string) => {
    const parts: string[] = []; let depth = 0, cur = '';
    for (const ch of s) {
      if (ch === '(') depth++;
      if (ch === ')') depth--;
      if (ch === ',' && depth === 0) { parts.push(cur); cur = ''; } else cur += ch;
    }
    if (cur.trim()) parts.push(cur);
    return parts;
  };
  const re = /((?:--[^\n]*\n)*)\s*CREATE TABLE IF NOT EXISTS\s+([a-z_]+)\s*\(/gi;
  for (let m; (m = re.exec(sql)); ) {
    let depth = 1, i = re.lastIndex;
    while (i < sql.length && depth > 0) { if (sql[i] === '(') depth++; else if (sql[i] === ')') depth--; i++; }
    const body = sql.slice(re.lastIndex, i - 1).replace(/--[^\n]*/g, '');
    const cols: Col[] = [];
    for (const part of splitTop(body)) {
      const t = part.trim().replace(/\s+/g, ' ');
      if (!t || /^(PRIMARY|UNIQUE|FOREIGN|CHECK|CONSTRAINT)\b/i.test(t)) continue;
      const mm = /^([a-z_][a-z0-9_]*)\s+(.*)$/i.exec(t);
      if (mm) cols.push({ name: mm[1], type: mm[2].split(/\s+(?:NOT NULL|NULL|DEFAULT|PRIMARY|REFERENCES|CHECK|UNIQUE)\b/i)[0], later: false });
    }
    const note = m[1].split('\n').map((l) => l.replace(/^--\s?/, '').trim()).filter(Boolean).join(' ');
    tables.set(m[2], { cols, note });
  }
  for (const m of sql.matchAll(/ALTER TABLE\s+([a-z_]+)\s+ADD COLUMN IF NOT EXISTS\s+([a-z_][a-z0-9_]*)\s+([^,;\n]+)/gi)) {
    const t = tables.get(m[1]);
    if (t && !t.cols.some((c) => c.name === m[2])) t.cols.push({ name: m[2], type: m[3].split(/\s+(?:NOT NULL|NULL|DEFAULT|PRIMARY|REFERENCES|CHECK|UNIQUE)\b/i)[0].trim(), later: true });
  }
  let md = `---\ntitle: Database schema\n---\n\n# Database schema\n\n${GENERATED('db/schema.sql')}\n`;
  md += 'PostgreSQL 15 or newer. `db/schema.sql` is applied idempotently at API startup and is **additive**: tables and columns are created if missing and never dropped. Column types are shown as written in the schema; columns marked *added later* arrived through an `ALTER TABLE` in a newer release.\n\n';
  md += `There are **${tables.size}** tables.\n\n`;
  md += [...tables.keys()].sort().map((t) => `[\`${t}\`](#${t.replace(/_/g, '-')})`).join(' · ') + '\n';
  for (const name of [...tables.keys()].sort()) {
    const t = tables.get(name)!;
    md += `\n## ${name}\n\n${t.note ? t.note + '\n\n' : ''}| Column | Type | |\n| --- | --- | --- |\n`;
    for (const c of t.cols) md += `| \`${c.name}\` | \`${esc(c.type)}\` | ${c.later ? 'added later' : ''} |\n`;
  }
  out('reference/schema.md', md);
}

// ---------------------------------------------------------------------------------------------------------------------------
// Agent job kinds
// ---------------------------------------------------------------------------------------------------------------------------
{
  const go = read('agent', 'main.go');
  const descriptions: Record<string, string> = JSON.parse(readFileSync(join(here, 'job-descriptions.json'), 'utf8'));
  const start = go.indexOf('switch j.Kind {');
  const kinds = new Set<string>();
  for (const m of go.slice(start).matchAll(/^\tcase ((?:"[a-z.-]+"(?:, )?)+):/gm)) for (const k of m[1].matchAll(/"([a-z.-]+)"/g)) kinds.add(k[1]);
  for (const m of go.matchAll(/j\.Kind == "([a-z.-]+)"/g)) kinds.add(m[1]);
  for (const k of kinds) if (!descriptions[k]) problems.push(`agent job kind ${k} has no entry in scripts/job-descriptions.json`);
  for (const k of Object.keys(descriptions)) if (k !== '_comment' && !kinds.has(k)) problems.push(`job kind ${k} is described but the agent no longer handles it`);
  let md = `---\ntitle: Agent job kinds\n---\n\n# Agent job kinds\n\n${GENERATED('agent/main.go and scripts/job-descriptions.json')}\n`;
  md += 'Every job the panel can send to a node. The agent leases jobs one at a time per server; see the [agent protocol](/api/agent-protocol). Unknown kinds are failed with an error.\n\n| Kind | What it does |\n| --- | --- |\n';
  for (const k of [...kinds].sort()) md += `| \`${k}\` | ${esc(descriptions[k] ?? '')} |\n`;
  out('reference/jobs.md', md);
}

// ---------------------------------------------------------------------------------------------------------------------------
// API reference
// ---------------------------------------------------------------------------------------------------------------------------
{
  const specPath = join(site, 'generated', 'openapi.json');
  rmSync(join(docs, 'api', 'reference'), { recursive: true, force: true });
  if (!existsSync(specPath)) {
    problems.push('generated/openapi.json is missing: run `npm run snapshot` (needs PostgreSQL, see docs-site/README.md)');
  } else {
    const spec = JSON.parse(readFileSync(specPath, 'utf8'));
    const byTag = new Map<string, { method: string; path: string; op: any }[]>();
    for (const [path, ops] of Object.entries<any>(spec.paths)) {
      for (const [method, op] of Object.entries<any>(ops)) {
        const tag = (op.tags?.[0] as string) || 'Other';
        if (!byTag.has(tag)) byTag.set(tag, []);
        byTag.get(tag)!.push({ method: method.toUpperCase(), path, op });
      }
    }
    const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
    const accessText: Record<string, string> = {
      public: 'No authentication',
      session: 'Signed-in user (browser session)',
      admin: 'Administrator',
      agent: 'Node agent credential',
      token: 'API token',
    };
    const order = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE'];
    const tags = [...byTag.keys()].sort((a, b) => (a.startsWith('Undocumented') ? 1 : 0) - (b.startsWith('Undocumented') ? 1 : 0) || a.localeCompare(b));
    let undocumented = 0, total = 0;
    for (const tag of tags) {
      const ops = byTag.get(tag)!.sort((a, b) => a.path.localeCompare(b.path) || order.indexOf(a.method) - order.indexOf(b.method));
      let md = `---\ntitle: ${tag.replace(/:/g, ' -')}\n---\n\n# ${tag}\n\n${GENERATED('GET /api/openapi.json')}\n`;
      for (const { method, path, op } of ops) {
        total++;
        if (op.summary === 'Undocumented') undocumented++;
        const params = (op.parameters || []).map((p: any) => `\`${p.name}\``).join(', ');
        md += `\n### ${method} \`${path}\` {#${method.toLowerCase()}-${slug(path)}}\n\n${op.summary}\n\n`;
        md += `- **Access:** ${accessText[op['x-access']] ?? op['x-access']}${op['x-token-scope'] ? `; also reachable with an API token that has the \`${op['x-token-scope']}\` scope` : ''}\n`;
        if (params) md += `- **Path parameters:** ${params}\n`;
        const body = op.requestBody?.content?.['application/json']?.schema?.description;
        if (body) md += `- **Body:** ${esc(body)}\n`;
      }
      out(`api/reference/${slug(tag)}.md`, md);
    }
    let idx = `---\ntitle: Endpoint reference\n---\n\n# Endpoint reference\n\n${GENERATED('GET /api/openapi.json')}\n`;
    idx += `Fledge **${spec.info.version}**, ${total} operations. Conventions: [Errors, paging, limits](/api/conventions); authentication: [Authentication](/api/authentication). The same description is served by the API itself at \`/api/openapi.json\` (administrators) and rendered in the panel under **API**.\n\n`;
    idx += '| Area | Operations |\n| --- | --- |\n';
    for (const tag of tags) idx += `| [${tag}](/api/reference/${slug(tag)}) | ${byTag.get(tag)!.length} |\n`;
    if (undocumented) idx += `\n${undocumented} operations are not documented yet and are listed under the *Undocumented* areas with their method and path only.\n`;
    out('api/reference/index.md', idx);
    writeFileSync(join(site, 'generated', 'coverage.json'), JSON.stringify({ total, undocumented }));
  }
}

if (problems.length) {
  console.error('Docs generation found problems:\n - ' + problems.join('\n - '));
  process.exit(1);
}
console.log('Generated the reference pages.');
