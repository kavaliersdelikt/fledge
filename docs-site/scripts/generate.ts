// Generates the reference pages from the repository sources, so they cannot drift from the code:
//   - API reference           from generated/openapi.json (see snapshot-openapi.mjs)
//   - environment variables   from .env.example, compose.yaml usage and scripts/env-descriptions.json
//   - plugin permissions etc. from api/src/plugins/manifest.ts and the plugin host limits
//   - notification events     from api/src/notifications.ts
//   - database schema         from db/schema.sql
//   - agent job kinds         from agent/main.go and scripts/job-descriptions.json
//   - release notes           from docs/releases/*.md
//
//   node ../api/node_modules/tsx/dist/cli.mjs scripts/generate.ts
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EVENTS } from '../../api/src/notifications.ts';
import { KNOWN_HOOKS, FIXED_PERMISSIONS, describePermission, API_VERSION } from '../../api/src/plugins/manifest.ts';
import { defaultLimits } from '../../plugins/host/src/sandbox.ts';

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, '..');
const repo = join(site, '..');
const docs = join(site, 'docs');
const read = (...p: string[]) => readFileSync(join(repo, ...p), 'utf8').replace(/\r\n/g, '\n');
const out = (path: string, text: string) => {
  const file = join(docs, path);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text.endsWith('\n') ? text : text + '\n');
};
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const GENERATED = (what: string) => `<!-- Generated by docs-site/scripts/generate.ts from ${what}. Do not edit by hand. -->\n`;
const problems: string[] = [];

// ---------------------------------------------------------------------------------------------------------------------------
// Release notes
// ---------------------------------------------------------------------------------------------------------------------------
{
  const dir = join(repo, 'docs', 'releases');
  rmSync(join(docs, 'releases'), { recursive: true, force: true });
  const names = readdirSync(dir).filter((f) => /^v\d.*\.md$/.test(f)).sort((a, b) => b.localeCompare(a, undefined, { numeric: true }));
  const GH = 'https://github.com/kavaliersdelikt/fledge/blob/main/';
  for (const f of names) {
    let text = read('docs', 'releases', f);
    const version = f.replace(/\.md$/, '');
    // Links to other repository files become GitHub links; links between release notes stay local.
    text = text.replace(/\]\((?!https?:|#|\/|mailto:)([^)\s]+)\)/g, (_m, target: string) => {
      if (/^v\d[^/]*\.md(#.*)?$/.test(target)) return `](${target.replace(/\.md/, '')})`;
      const clean = target.replace(/^(\.\.\/)+/, '').replace(/^\.\//, '');
      return `](${GH}${clean.startsWith('docs/') || !target.startsWith('..') ? (target.startsWith('..') ? clean : 'docs/releases/' + clean) : clean})`;
    });
    // Stray angle brackets outside code would be parsed as HTML by the site generator.
    text = text.split(/(```[\s\S]*?```)/g).map((part, i) => (i % 2 ? part : part.replace(/<(?![/a-zA-Z!])/g, '&lt;'))).join('');
    out(`releases/${f}`, `---\ntitle: ${version}\n---\n\n${text}`);
  }
  out('releases/index.md', `---\ntitle: Release notes\n---\n\n# Release notes\n\n${GENERATED('docs/releases/*.md')}\nFledge versions have four parts: \`major.minor.patch.release\`. Notes for every release:\n\n${names.map((f) => `- [${f.replace(/\.md$/, '')}](/releases/${f.replace(/\.md$/, '')})`).join('\n')}\n\nThe newest release is also on the [GitHub releases page](https://github.com/kavaliersdelikt/fledge/releases).\n`);
}

// ---------------------------------------------------------------------------------------------------------------------------
// Environment variables
// ---------------------------------------------------------------------------------------------------------------------------
{
  type Desc = { scope: string; group: string; default?: string; description: string };
  const described: Record<string, Desc> = JSON.parse(readFileSync(join(here, 'env-descriptions.json'), 'utf8'));
  delete (described as any)._comment;
  const example = read('.env.example');
  const inExample = new Map<string, { value: string; commented: boolean }>();
  for (const line of example.split('\n')) {
    const m = /^(#\s*)?([A-Z][A-Z0-9_]+)=(.*)$/.exec(line);
    if (m) inExample.set(m[2], { value: m[3].replace(/\s+#.*$/, '').trim(), commented: !!m[1] });
  }
  // Every variable the code reads must be described.
  const used = new Set<string>();
  const scan = (text: string, re: RegExp) => { for (const m of text.matchAll(re)) used.add(m[1]); };
  const walk = (dir: string, exts: string[]) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.name === 'node_modules' || e.name === 'test' || e.name.startsWith('.')) continue;
      const p = join(dir, e.name);
      if (e.isDirectory()) walk(p, exts);
      else if (exts.some((x) => e.name.endsWith(x)) && !e.name.endsWith('_test.go')) {
        const t = readFileSync(p, 'utf8');
        scan(t, /process\.env\.([A-Z][A-Z0-9_]+)/g);
        scan(t, /\be\.([A-Z][A-Z0-9_]{3,})\b/g);
        scan(t, /(?:os\.Getenv|env)\("([A-Z][A-Z0-9_]+)"/g);
      }
    }
  };
  walk(join(repo, 'api', 'src'), ['.ts']);
  walk(join(repo, 'plugins', 'host', 'src'), ['.ts']);
  walk(join(repo, 'agent'), ['.go']);
  scan(read('compose.yaml'), /\$\{([A-Z][A-Z0-9_]+)[:?-]/g);
  for (const k of inExample.keys()) used.add(k);
  for (const k of [...used].sort()) if (!described[k]) problems.push(`environment variable ${k} is used but has no entry in scripts/env-descriptions.json`);
  for (const k of Object.keys(described)) if (!used.has(k) && !['INSTALL_PLUGIN_WAIT_ATTEMPTS', 'UPDATE_POLL_SECONDS', 'FLEDGE_DOCKER_TEST_IMAGE'].includes(k)) problems.push(`environment variable ${k} is described but no longer used`);

  const groups: [string, string, string][] = [
    ['required', 'Required', 'Set these in `.env` before the first start.'],
    ['deployment', 'Deployment', 'Set in `.env` when your setup needs them.'],
    ['seed', 'Optional seeds', 'These only seed a form in the panel before it is first saved there; afterwards the database wins.'],
    ['process', 'Set by Compose or the image', 'Normally not edited. Listed for people running the API outside Compose.'],
    ['agent', 'Node agent', 'Environment of the `fledge-agent` service on a node (the connector writes them into the unit).'],
    ['test', 'Test switches', '**Never set these in production.** They exist for the test suites.'],
  ];
  let md = `---\ntitle: Environment variables\n---\n\n# Environment variables\n\n${GENERATED('.env.example, compose.yaml, scripts/env-descriptions.json and a scan of the code')}\n`;
  md += 'Every variable the code reads is listed. See [Configuration](/operate/configuration) for how the pieces fit.\n';
  for (const [key, title, intro] of groups) {
    const items = Object.entries(described).filter(([, d]) => d.group === key).sort(([a], [b]) => a.localeCompare(b));
    if (!items.length) continue;
    md += `\n## ${title}\n\n${intro}\n\n| Variable | Used by | Default | Meaning |\n| --- | --- | --- | --- |\n`;
    for (const [name, d] of items) {
      const ex = inExample.get(name);
      const def = d.default ?? (ex && ex.value && !/REPLACE_WITH/.test(ex.value) ? ex.value : '');
      md += `| \`${name}\` | ${d.scope} | ${def ? `\`${esc(def)}\`` : ''} | ${esc(d.description)} |\n`;
    }
  }
  out('reference/environment.md', md);
}

// ---------------------------------------------------------------------------------------------------------------------------
// Plugin permissions, hooks, limits
// ---------------------------------------------------------------------------------------------------------------------------
{
  const mb = (n: number) => `${Math.round((n / (1 << 20)) * 10) / 10} MB`;
  let md = `---\ntitle: Plugin permissions and hooks\n---\n\n# Plugin permissions, hooks and limits\n\n${GENERATED('api/src/plugins/manifest.ts and plugins/host/src/sandbox.ts')}\nPlugin API version: **${API_VERSION}**. See [Manifest and permissions](/plugins/manifest) for how to use them.\n\n`;
  md += '## Permissions\n\n| Permission | What the administrator is told |\n| --- | --- |\n';
  md += `| \`network:<host>\` | ${esc(describePermission('network:example.org').replace('example.org', 'the named host'))}. \`<host>\` is a full domain or \`*.domain\`; wildcards over shared hosting platforms are refused |\n`;
  for (const p of FIXED_PERMISSIONS) md += `| \`${p}\` | ${esc(describePermission(p))} |\n`;
  md += '\n## Hooks\n\nA plugin needs the `hooks` permission to receive them.\n\n| Event |\n| --- |\n';
  for (const h of KNOWN_HOOKS) md += `| \`${h}\` |\n`;
  md += '\n## Setting field types\n\n`string` (`pattern`, `placeholder`), `number` (`min`, `max`), `boolean`, `select` (`options`), `secret` (encrypted at rest, write-only).\n';
  md += '\n## Sandbox limits per call\n\n| Limit | Value |\n| --- | --- |\n';
  md += `| Memory | ${mb(defaultLimits.memoryBytes)} |\n| Stack | ${mb(defaultLimits.stackBytes)} |\n| Run time | ${defaultLimits.deadlineMs / 1000} s |\n| Requests | ${defaultLimits.maxFetches} |\n| Bytes per response | ${mb(defaultLimits.maxFetchBytes)} |\n| Bytes per call (all responses) | ${mb(defaultLimits.maxTotalBytes)} |\n| Result size | ${mb(defaultLimits.maxResultBytes)} |\n| Log lines | ${defaultLimits.maxLogLines} |\n| Storage | ${Math.round(defaultLimits.maxStorageBytes / 1024)} KB |\n`;
  out('reference/plugin-manifest.md', md);
}

